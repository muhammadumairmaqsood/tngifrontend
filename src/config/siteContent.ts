type SiteContentEntry = (typeof STATIC_SITE_CONTENT)[number];

const SITE_CONTENT_BY_SLUG: Record<string, SiteContentEntry> = STATIC_SITE_CONTENT.reduce(
  (acc, item) => {
    acc[item.slug] = item;
    return acc;
  },
  {} as Record<string, SiteContentEntry>
);

const unwrapGoogleViewerUrl = (url: string) => {
  if (!url.includes('docs.google.com/viewerng/viewer')) {
    return null;
  }

  try {
    const parsed = new URL(url);
    return parsed.searchParams.get('url');
  } catch {
    return null;
  }
};

const extractGoogleDriveFileId = (url: string) => {
  const filePathMatch = url.match(/\/file\/d\/([^/]+)/);
  if (filePathMatch?.[1]) {
    return filePathMatch[1];
  }

  try {
    const parsed = new URL(url);
    const fileId = parsed.searchParams.get('id');
    return fileId || null;
  } catch {
    return null;
  }
};

const buildGoogleDriveLinks = (fileId: string) => ({
  embedUrl: `https://drive.google.com/file/d/${fileId}/preview`,
  originalUrl: `https://drive.google.com/file/d/${fileId}/view`,
  downloadUrl: `https://drive.google.com/uc?export=download&id=${fileId}`,
});

const toGoogleDriveEmbedUrl = (url: string) => {
  if (url.includes('drive.google.com/file/')) {
    return url.replace('/view', '/preview').replace('/edit', '/preview');
  }

  return `https://drive.google.com/viewerng/viewer?embedded=true&url=${encodeURIComponent(
    url
  )}`;
};

const requireSiteContentLinks = (
  slug: string,
  options?: { requireGoogleDrive?: boolean }
) => {
  const entry = SITE_CONTENT_BY_SLUG[slug];

  if (!entry?.embed_url || !entry?.original_url) {
    throw new Error(`Missing embed/original URL for site content slug: ${slug}`);
  }

  const unwrappedEmbed = unwrapGoogleViewerUrl(entry.embed_url);
  const unwrappedOriginal = unwrapGoogleViewerUrl(entry.original_url);
  const candidateUrl = unwrappedOriginal || unwrappedEmbed || entry.original_url;
  const driveFileId = extractGoogleDriveFileId(candidateUrl);

  if (driveFileId) {
    return buildGoogleDriveLinks(driveFileId);
  }

  if (options?.requireGoogleDrive) {
    throw new Error(
      `Site content slug "${slug}" must use a Google Drive file link.`
    );
  }

  return {
    // Force Google Drive-compatible iframe embeds for document pages.
    embedUrl: toGoogleDriveEmbedUrl(candidateUrl),
    originalUrl: candidateUrl,
    downloadUrl: candidateUrl,
  };
};

